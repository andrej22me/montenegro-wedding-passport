"""Build SVG land, coast and road paths from OSM data (ODbL)."""
import json
import math
import os
import requests
from shapely.geometry import LineString, Point, box, MultiLineString
from shapely.ops import polygonize, unary_union, linemerge

S, W, N, E = 42.24, 18.48, 42.52, 18.92
SEA_POINTS = [(18.60, 42.28)]
WIDTH = 1000
KX = math.cos(math.radians((S + N) / 2))
SCALE = WIDTH / ((E - W) * KX)
HEIGHT = round((N - S) * SCALE)
UA = {"User-Agent": "AdriaticEventsWeddingSite/1.0"}
frame = box(W, S, E, N)


def overpass(query, cache):
    if os.path.exists(cache):
        with open(cache, encoding="utf-8") as f:
            return json.load(f)["elements"]
    res = requests.post(
        "https://overpass-api.de/api/interpreter",
        data={"data": query},
        headers=UA,
        timeout=180,
    )
    res.raise_for_status()
    with open(cache, "w", encoding="utf-8") as f:
        f.write(res.text)
    return res.json()["elements"]


def project(lon, lat):
    return ((lon - W) * KX * SCALE, (N - lat) * SCALE)


def line_path(geom, tol, closed=False):
    if geom is None or geom.is_empty:
        return ""
    geom = geom.simplify(tol, preserve_topology=True)
    parts = []

    def emit(coords):
        pts = [project(x, y) for x, y in coords]
        if len(pts) < 2:
            return
        d = "M" + "L".join(f"{x:.1f} {y:.1f}" for x, y in pts)
        if closed:
            d += "Z"
        parts.append(d)

    gt = geom.geom_type
    if gt == "Polygon":
        emit(geom.exterior.coords)
        for ring in geom.interiors:
            emit(ring.coords)
    elif gt == "MultiPolygon":
        for poly in geom.geoms:
            emit(poly.exterior.coords)
            for ring in poly.interiors:
                emit(ring.coords)
    elif gt == "LineString":
        emit(geom.coords)
    elif gt == "LinearRing":
        emit(geom.coords)
    elif gt in ("MultiLineString", "GeometryCollection"):
        for g in geom.geoms:
            p = line_path(g, 0, closed)
            if p:
                parts.append(p)
    return "".join(parts)


coast_ways = overpass(
    f"""
    [out:json][timeout:90];
    way["natural"="coastline"]({S - 0.02},{W - 0.02},{N + 0.02},{E + 0.02});
    out geom;
    """,
    "scripts/coastline_raw.json",
)
print("coast ways", len(coast_ways))

lines = [
    LineString([(p["lon"], p["lat"]) for p in w["geometry"]])
    for w in coast_ways
    if len(w.get("geometry") or []) > 1
]
noded = unary_union([*lines, frame.exterior])
polys = [p for p in polygonize(noded) if frame.contains(p.representative_point())]
sea_geom = unary_union([p for p in polys if any(p.contains(Point(s)) for s in SEA_POINTS)])
land = frame.difference(sea_geom).buffer(0)
print("land area", round(land.area / frame.area, 3))

coast = sea_geom.boundary.difference(frame.exterior.buffer(0.0008))

road_ways = overpass(
    f"""
    [out:json][timeout:90];
    way["highway"~"^(trunk|primary|secondary)$"]({S},{W},{N},{E});
    out geom;
    """,
    "scripts/roads_raw.json",
)
print("road ways", len(road_ways))
road_lines = []
for w in road_ways:
    geom = w.get("geometry") or []
    if len(geom) < 2:
        continue
    line = LineString([(p["lon"], p["lat"]) for p in geom])
    clipped = line.intersection(frame)
    if not clipped.is_empty:
        road_lines.append(clipped)
roads = linemerge(unary_union(road_lines)) if road_lines else MultiLineString()

land_d = line_path(land, 0.00016, closed=True)
coast_d = line_path(coast, 0.00012, closed=False)
roads_d = line_path(roads, 0.00025, closed=False)
print("chars land/coast/roads", len(land_d), len(coast_d), len(roads_d))

os.makedirs("src/data", exist_ok=True)
with open("src/data/mapGeo.ts", "w", encoding="utf-8") as f:
    f.write("// Generated by scripts/build_coastline.py from OpenStreetMap data (ODbL).\n")
    f.write(f"export const MAP_BOUNDS = {json.dumps({'west': W, 'east': E, 'south': S, 'north': N})};\n")
    f.write(f"export const MAP_SIZE = {{ width: {WIDTH}, height: {HEIGHT} }};\n")
    f.write(f"const KX = {KX!r};\nconst SCALE = {SCALE!r};\n")
    f.write(
        "export const project = (lon: number, lat: number) => ({\n"
        "  x: (lon - MAP_BOUNDS.west) * KX * SCALE,\n"
        "  y: (MAP_BOUNDS.north - lat) * SCALE,\n"
        "});\n"
    )
    f.write(f"export const LAND_PATH =\n  {json.dumps(land_d)};\n")
    f.write(f"export const COAST_PATH =\n  {json.dumps(coast_d)};\n")
    f.write(f"export const ROADS_PATH =\n  {json.dumps(roads_d)};\n")
